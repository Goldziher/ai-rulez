const (
	aliasPluginConfig = `version = "5.0"
name = "acme"
presets = ["claude"]
gitignore = false

[plugin]
name = "acme"
description = "Acme skills."
version = "1.4.0"
repository = "https://github.com/acme/skills"
runtimes = ["claude", "cursor"]

[plugin.author]
name = "Jane"
`
	aliasMarketplaceConfig = `version = "5.0"
name = "root"
presets = ["claude"]
gitignore = false

[marketplace]
name = "acme"
description = "Acme plugins."
members = ["plugin"]

[marketplace.owner]
name = "Jane"
`
	aliasDeployDescription = "Use when deploying the service to production; not for local runs."
	aliasDeploySkill       = "---\nname: deploy\ndescription: " + aliasDeployDescription + "\n---\n\n# Deploy\n\nRun the pipeline.\n"
)

// aliasProject is the layout of #485: a marketplace at the repository root
// whose member plugin is configured in plugin/.ai-rulez, the bundle `generate
// --plugin` writes into plugin/, and a byte-identical public export of the
// generated skill at skills/deploy. It returns the root and the generated bytes.
func aliasProject(t *testing.T, env *isoEnv) (root string, generated []byte) {
	t.Helper()
	root = t.TempDir()
	writeTree(t, root, map[string]string{
		".ai-rulez/config.toml":                   aliasMarketplaceConfig,
		"plugin/.ai-rulez/config.toml":            aliasPluginConfig,
		"plugin/.ai-rulez/skills/deploy/SKILL.md": aliasDeploySkill,
	})
	env.commitAll(root, "init")
	res := env.run(root, "generate", "--plugin")
	require.Equal(t, 0, res.ExitCode, "generate --plugin: %s%s", res.Stdout, res.Stderr)
	generated, err := os.ReadFile(filepath.Join(root, "plugin", "skills", "deploy", "SKILL.md"))
	require.NoError(t, err)
	require.Contains(t, string(generated), "AI-RULEZ :: GENERATED FILE")
	writeTree(t, root, map[string]string{"skills/deploy/SKILL.md": string(generated)})
	env.commitAll(root, "generate")
	return root, generated
}

func validateOutput(t *testing.T, env *isoEnv, dir string) string {
	t.Helper()
	res := env.run(dir, "validate", "--strict", "--no-local")
	return res.Stdout + res.Stderr
}

// TestGeneratedSkillAliasesE2E: the generated copies are the configured skill,
// not second definitions of it, so neither the repository root nor the plugin
// reports AR701 or AR703. A copy is the skill only while its bytes are what the
// generator renders from it now.
func TestGeneratedSkillAliasesE2E(t *testing.T) {
	tests := []struct {
		name string
		edit func(t *testing.T, root string, generated []byte)
		want bool // AR701 or AR703 reported
	}{
		{name: "generated copies and a public export"},
		{
			name: "public export with CRLF line endings",
			edit: func(t *testing.T, root string, generated []byte) {
				writeTree(t, root, map[string]string{"skills/deploy/SKILL.md": strings.ReplaceAll(string(generated), "\n", "\r\n")})
			},
		},
		{
			name: "edited public export",
			edit: func(t *testing.T, root string, generated []byte) {
				writeTree(t, root, map[string]string{"skills/deploy/SKILL.md": strings.Replace(string(generated), "Run the pipeline.", "Run the pipeline by hand.", 1)})
			},
			want: true,
		},
		{
			name: "stale copies beside a third-party duplicate",
			edit: func(t *testing.T, root string, _ []byte) {
				writeTree(t, root, map[string]string{
					"plugin/.ai-rulez/skills/deploy/SKILL.md": strings.Replace(aliasDeploySkill, aliasDeployDescription, "Use when rolling the service back after a failed release.", 1),
					".claude/skills/other/SKILL.md":           "---\nname: other\ndescription: " + aliasDeployDescription + "\n---\n\nMine.\n",
				})
			},
			want: true,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			env := newIsoEnv(t)
			root, generated := aliasProject(t, env)
			if tt.edit != nil {
				tt.edit(t, root, generated)
				env.commitAll(root, "edit")
			}
			for _, dir := range []string{root, filepath.Join(root, "plugin")} {
				out := validateOutput(t, env, dir)
				reported := strings.Contains(out, "AR701") || strings.Contains(out, "AR703")
				assert.Equal(t, tt.want, reported, "validate in %s:\n%s", dir, out)
			}
		})
	}
}

// TestGeneratedSkillAliasesThroughSymlinkE2E: validate run from the member
// through a symlinked path to the repository renders the same bundle as from
// the real path.
func TestGeneratedSkillAliasesThroughSymlinkE2E(t *testing.T) {
	env := newIsoEnv(t)
	root, _ := aliasProject(t, env)
	link := filepath.Join(t.TempDir(), "link")
	testutil.SymlinkOrSkip(t, root, link)
	for _, dir := range []string{link, filepath.Join(link, "plugin")} {
		out := validateOutput(t, env, dir)
		assert.NotContains(t, out, "AR701", dir)
		assert.NotContains(t, out, "AR703", dir)
	}
}

// TestGeneratedSkillAliasAtRootPluginE2E: a plugin configured at the repository
// root generates skills/<name> beside its definition; a copy of it elsewhere is
// the skill too.
func TestGeneratedSkillAliasAtRootPluginE2E(t *testing.T) {
	env := newIsoEnv(t)
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		".ai-rulez/config.toml":            aliasPluginConfig,
		".ai-rulez/skills/deploy/SKILL.md": aliasDeploySkill,
	})
	env.commitAll(root, "init")
	res := env.run(root, "generate", "--plugin")
	require.Equal(t, 0, res.ExitCode, "generate --plugin: %s%s", res.Stdout, res.Stderr)
	generated, err := os.ReadFile(filepath.Join(root, "skills", "deploy", "SKILL.md"))
	require.NoError(t, err)
	writeTree(t, root, map[string]string{"public/skills/deploy/SKILL.md": string(generated)})
	env.commitAll(root, "generate")

	out := validateOutput(t, env, root)
	assert.NotContains(t, out, "AR701")
	assert.NotContains(t, out, "AR703")
}

// TestMintedProvenanceIsNoAliasE2E: a header and a provenance sidecar are text
// anyone can produce, here by generating a throwaway plugin and copying its
// output and sidecar into the project. A hand-written skill that duplicates the
// project's own skill stays reported however its header reads.
func TestMintedProvenanceIsNoAliasE2E(t *testing.T) {
	env := newIsoEnv(t)
	forge := t.TempDir()
	writeTree(t, forge, map[string]string{
		".ai-rulez/config.toml":          strings.Replace(aliasPluginConfig, `name = "acme"`+"\npresets", `name = "forge"`+"\npresets", 1),
		".ai-rulez/skills/demo/SKILL.md": "---\nname: demo\ndescription: Use when demonstrating the project.\n---\n\nForged.\n",
	})
	env.commitAll(forge, "init")
	res := env.run(forge, "generate", "--plugin")
	require.Equal(t, 0, res.ExitCode, "generate --plugin: %s%s", res.Stdout, res.Stderr)
	minted, err := os.ReadFile(filepath.Join(forge, "skills", "demo", "SKILL.md"))
	require.NoError(t, err)
	sidecar, err := os.ReadFile(filepath.Join(forge, ".ai-rulez-generated.json"))
	require.NoError(t, err)

	root := t.TempDir()
	writeTree(t, root, map[string]string{
		".ai-rulez/config.toml":          "version = \"5.0\"\nname = \"root\"\npresets = [\"claude\"]\ngitignore = false\n",
		".ai-rulez/skills/demo/SKILL.md": "---\nname: demo\ndescription: Use when demonstrating the project.\n---\n\nThe real one.\n",
		"skills/demo/SKILL.md":           string(minted),
		".ai-rulez-generated.json":       string(sidecar),
	})
	env.commitAll(root, "init")

	out := validateOutput(t, env, root)
	assert.Contains(t, out, "AR701")
	assert.Contains(t, out, "AR703")
}
