func TestJSONReportNamesTheOutputSourceOfAFinding(t *testing.T) {
	t.Cleanup(testutil.CleanupTestBinary)
	dir := testutil.CreateTempDir(t)
	writeLintFile(t, dir, "skills/gen/SKILL.md", "<!-- Generated by ai-rulez -->\n"+noDescription)

	res := testutil.RunCLI(t, dir, "validate", "--strict", "--outputs", "--format", "json")

	var doc struct {
		Findings []map[string]any `json:"findings"`
	}
	require.NoError(t, json.Unmarshal([]byte(res.Stdout), &doc), res.Stdout)
	require.Len(t, doc.Findings, 1, res.Stdout)
	assert.Equal(t, "AR801", doc.Findings[0]["code"])
	assert.Equal(t, "output", doc.Findings[0]["source"])
	assert.Equal(t, 2, res.ExitCode)
}

// Scenario (d): --outputs lints what generate writes, and a problem that the
// authored source already has is reported once, at the source.
func TestOutputsFlagLintsGeneratedFilesOnce(t *testing.T) {
	t.Cleanup(testutil.CleanupTestBinary)
	dir := testutil.CreateTempDir(t)
	gitInitAgents(t, dir)
	writeLintFile(t, dir, ".ai-rulez/config.toml", e2eV5Config)
	writeLintFile(t, dir, ".ai-rulez/skills/loose/SKILL.md", noDescription)
	testutil.RunCLIExpectSuccess(t, dir, "generate", "--yes")
	require.FileExists(t, filepath.Join(dir, ".claude", "skills", "loose", "SKILL.md"))

	for _, args := range [][]string{{"validate", "--strict"}, {"validate", "--strict", "--outputs"}} {
		res := testutil.RunCLI(t, dir, args...)
		assert.Equal(t, 2, res.ExitCode, "%v: %s%s", args, res.Stdout, res.Stderr)
		assert.Equal(t, 1, strings.Count(res.Stdout, " warning AR801 "), "%v reports the skill once:\n%s", args, res.Stdout)
		assert.Contains(t, res.Stdout, ".ai-rulez/skills/loose/SKILL.md", "the finding sits at the authored path")
	}
}

func TestOutputsFlagIsRefusedWithConfigOnly(t *testing.T) {
	t.Cleanup(testutil.CleanupTestBinary)
	dir := testutil.CreateTempDir(t)
	writeLintFile(t, dir, ".ai-rulez/config.toml", e2eV5Config)

	res := testutil.RunCLI(t, dir, "validate", "--config-only", "--outputs")

	assert.Equal(t, 1, res.ExitCode, res.Stdout+res.Stderr)
}
