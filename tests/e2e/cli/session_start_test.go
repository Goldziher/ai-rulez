// sessionStartProject generates a project for Claude Code in a git work tree and returns its directory.
func sessionStartProject(t *testing.T, config string) string {
	t.Helper()
	t.Cleanup(testutil.CleanupTestBinary)
	dir := testutil.CreateTempDir(t)
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not available")
	}
	out, err := gitutil.CommandNoContext(dir, "init", "-q").CombinedOutput()
	require.NoError(t, err, string(out))
	require.NoError(t, os.MkdirAll(filepath.Join(dir, ".ai-rulez", "rules"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(dir, ".ai-rulez", "config.toml"), []byte(config), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(dir, ".ai-rulez", "rules", "style.md"), []byte("# style\n\nBe terse.\n"), 0o644))
	testutil.RunCLIExpectSuccess(t, dir, "generate", "--yes")
	return dir
}

// hookCommands returns the commands of the SessionStart entries of .claude/settings.json.
func hookCommands(t *testing.T, dir string) []string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(dir, ".claude", "settings.json"))
	require.NoError(t, err)
	var doc struct {
		Hooks map[string][]struct {
			Hooks []struct {
				Command string `json:"command"`
				Timeout int    `json:"timeout"`
			} `json:"hooks"`
		} `json:"hooks"`
	}
	var kept []string
	for _, line := range strings.Split(string(data), "\n") {
		if !strings.HasPrefix(strings.TrimSpace(line), "//") {
			kept = append(kept, line) // the file may be JSONC
		}
	}
	require.NoError(t, json.Unmarshal([]byte(strings.Join(kept, "\n")), &doc))
	var out []string
	for _, g := range doc.Hooks["SessionStart"] {
		for _, h := range g.Hooks {
			out = append(out, h.Command)
		}
	}
	return out
}

type hookRun struct {
	stdout, stderr string
	code           int
}

// runHook executes the emitted hook command line with sh, the way the harness does, in an environment
// that holds only PATH (the stub directory), HOME and the given variables.
func runHook(t *testing.T, dir, command, stubDir, stdin string, env ...string) hookRun {
	t.Helper()
	if runtime.GOOS == "windows" {
		t.Skip("the hook command and its stubs are POSIX sh scripts")
	}
	sh, err := exec.LookPath("sh")
	require.NoError(t, err)
	if _, err := os.Lstat(filepath.Join(stubDir, "sh")); err != nil {
		itestutil.SymlinkOrSkip(t, sh, filepath.Join(stubDir, "sh")) // the emitted command starts with sh
	}
	for _, tool := range []string{"mktemp", "rmdir"} { // the neutral directory is made and removed with these
		if p, err := exec.LookPath(tool); err == nil {
			if _, err := os.Lstat(filepath.Join(stubDir, tool)); err != nil {
				itestutil.SymlinkOrSkip(t, p, filepath.Join(stubDir, tool))
			}
		}
	}
	cmd := exec.Command(sh, "-c", command)
	cmd.Dir = dir
	cmd.Env = append([]string{"PATH=" + stubDir, "HOME=" + t.TempDir(), "TMPDIR=" + t.TempDir()}, env...)
	cmd.Stdin = strings.NewReader(stdin)
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	err = cmd.Run()
	code := 0
	var exitErr *exec.ExitError
	if errors.As(err, &exitErr) {
		code = exitErr.ExitCode()
	} else {
		require.NoError(t, err)
	}
	return hookRun{stdout: stdout.String(), stderr: stderr.String(), code: code}
}

// stub writes an executable shell script named name into dir that appends "name args" to log, its
// working directory to log+".cwd", and exits with code.
func stub(t *testing.T, dir, log, name string, code int) {
	t.Helper()
	script := "#!/bin/sh\necho \"" + name + " $*\" >> \"" + log + "\"\necho \"" + name + " $(pwd -P)\" >> \"" + log + ".cwd\"\nexit " +
		string(rune('0'+code)) + "\n"
	require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(script), 0o755))
}

func readStubLog(t *testing.T, log string) []string {
	t.Helper()
	data, err := os.ReadFile(log)
	if os.IsNotExist(err) {
		return nil
	}
	require.NoError(t, err)
	return strings.Split(strings.TrimSpace(string(data)), "\n")
}

func TestSessionStartE2E_GeneratedSettingsAndLifecycle(t *testing.T) {
	dir := sessionStartProject(t, sessionStartProjectConfig)

	t.Run("the hook is generated by default, once, with a bounded timeout", func(t *testing.T) {
		commands := hookCommands(t, dir)

		require.Len(t, commands, 1)
		assert.Contains(t, commands[0], "ai-rulez session-start")
		assert.Contains(t, commands[0], "npx -y ai-rulez@latest")
		assert.Contains(t, commands[0], "uvx --from ai-rulez@latest")
		assert.Contains(t, commands[0], "CLAUDE_CODE_REMOTE")
	})
	t.Run("generate --check is clean", func(t *testing.T) {
		result := testutil.RunCLI(t, dir, "generate", "--check")

		assert.Equal(t, 0, result.ExitCode, result.Stdout+result.Stderr)
	})
	t.Run("a second generate changes nothing and does not announce the hook again", func(t *testing.T) {
		before := hookCommands(t, dir)

		result := testutil.RunCLIExpectSuccess(t, dir, "generate")

		assert.Equal(t, before, hookCommands(t, dir))
		assert.NotContains(t, result.Stderr, "session-start")
	})
	t.Run("clean removes the managed hook", func(t *testing.T) {
		testutil.RunCLIExpectSuccess(t, dir, "clean", "--yes")

		_, err := os.Stat(filepath.Join(dir, ".claude", "settings.json"))
		if err == nil {
			assert.Empty(t, hookCommands(t, dir))
		}
	})
}

