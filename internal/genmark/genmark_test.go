package genmark

import (
	"testing"

	"github.com/stretchr/testify/assert"

	"github.com/Goldziher/ai-rulez/v5/internal/templates"
)

const realHeader = "<!--\n🤖 AI-RULEZ :: GENERATED FILE — DO NOT EDIT\nProject: t\n-->\n\n"

func TestIsGeneratedOutput(t *testing.T) {
	body := "# Rules\n\nRun the tests.\n"
	hash := templates.HashContent(body)
	bodyOnlyHash := "---\nname: s\n# Content-Hash: " + hash + "\n---\n" + body

	tests := []struct {
		name string
		path string
		data string
		want bool
	}{
		{name: "the real header", path: "AGENTS.md", data: realHeader + body, want: true},
		{name: "the old banner", path: "AGENTS.md", data: "<!-- Generated by ai-rulez from x.md. -->\n" + body, want: true},
		{name: "a byte order mark before the header", path: "AGENTS.md", data: "\xef\xbb\xbf" + realHeader + body, want: true},
		{name: "a banner with a Content-Hash that verifies", path: "AGENTS.md",
			data: "<!--\nGENERATED FILE\nContent-Hash: " + hash + "\n-->\n\n" + body, want: true},
		{name: "a banner with a Content-Hash the body does not match", path: "AGENTS.md",
			data: "<!--\nGENERATED FILE\nContent-Hash: " + hash + "\n-->\n\n# Changed\n", want: false},
		{name: "a skill with only a verifying Content-Hash in the frontmatter", path: ".claude/skills/s/SKILL.md", data: bodyOnlyHash, want: true},
		{name: "an agent with only a verifying Content-Hash in the frontmatter", path: ".claude/agents/a.md", data: bodyOnlyHash, want: true},
		{name: "a skill whose body was edited", path: ".claude/skills/s/SKILL.md", data: bodyOnlyHash + "extra\n", want: false},
		{name: "a Content-Hash line in the body is body text", path: "AGENTS.md",
			data: "# Notes\n\nContent-Hash: " + hash + "\n", want: false},
		{name: "a marker after a heading", path: "AGENTS.md", data: "# Notes\n\n<!-- Generated by ai-rulez -->\n", want: false},
		{name: "a marker in the second comment", path: "AGENTS.md", data: "<!-- todo -->\n<!-- Generated by ai-rulez -->\n" + body, want: false},
		{name: "plain handwritten text", path: "AGENTS.md", data: body, want: false},
		{name: "an empty file", path: "AGENTS.md", data: "", want: false},
		{name: "a line comment header in a non-markdown file", path: "rules.yaml", data: "# GENERATED FILE - DO NOT EDIT\nkey: v\n", want: true},
		{name: "a marker below the first line comments of a non-markdown file", path: "rules.yaml", data: "key: v\n# GENERATED FILE\n", want: false},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, IsGeneratedOutput(tc.path, []byte(tc.data)))
		})
	}
}
