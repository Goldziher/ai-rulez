// Package genmark decides whether a file is one ai-rulez generated. The generator
// and the linter share it, so "this file is an output" means the same thing to
// the code that writes it and to the code that decides whether to lint it as a
// source.
//
// A file is generated when its leading header says so: a generated-file banner
// in the first comment after the optional frontmatter, or a Content-Hash line in
// the frontmatter. A marker anywhere else (documentation that quotes the banner,
// a hand-written rule that mentions it) does not count. When the header stores a
// Content-Hash, the body must still hash to it, otherwise the file was edited
// and is judged as hand-written.
package genmark

import (
	"bufio"
	"bytes"
	"io"
	"path/filepath"
	"strings"

	"github.com/Goldziher/ai-rulez/v5/internal/frontmatter"
	"github.com/Goldziher/ai-rulez/v5/internal/templates"
)

// MaxHashedTrailingNewlines is the longest run of trailing newlines a
// Content-Hash covers. The hash is taken before generate normalizes the file
// to one trailing newline, so BodyEdited cannot see how many the rendering had
// and tries every run up to this bound; the generator caps the run at the same
// bound so that every hash it writes is one of those shapes.
const MaxHashedTrailingNewlines = 3

// maxHeaderLines bounds how far ScanHashes reads past a frontmatter block (or
// into a file without one).
const maxHeaderLines = 60

// bannerScanLimit bounds how much of a file the banner check reads.
const bannerScanLimit = 16 * 1024

const (
	extHTML = ".html"
	bom     = "\xef\xbb\xbf" // the UTF-8 byte order mark
)

// IsGeneratedOutput reports whether data, the content of the file at path, is a
// file ai-rulez generated. The leading header must carry a generated-file banner
// or a Content-Hash; a stored Content-Hash must verify against the body.
func IsGeneratedOutput(path string, data []byte) bool {
	data = bytes.TrimPrefix(data, []byte(bom))
	stored, _, inFrontmatter := ScanHashes(bytes.NewReader(data))
	banner := HasBanner(path, data)
	if stored == "" {
		return banner
	}
	if !banner && !inFrontmatter {
		return false // a Content-Hash line outside the header is body text
	}
	return !BodyEdited(stored, string(data), path)
}

// HasBanner reports whether data starts with a generated-file banner: the first
// comment after the optional frontmatter. For markdown that is an HTML comment,
// for any other extension also a leading block of line comments.
func HasBanner(path string, data []byte) bool {
	if len(data) > bannerScanLimit {
		data = data[:bannerScanLimit]
	}
	text := strings.TrimPrefix(string(data), bom)
	if end, _ := FrontmatterEnd(text); end > 0 {
		text = text[end:]
	}
	text = strings.TrimLeft(text, " \t\r\n")
	if strings.HasPrefix(text, "<!--") {
		if end := strings.Index(text, "-->"); end >= 0 {
			text = text[:end]
		}
		return containsBannerMarker(text)
	}
	if IsMarkdownExt(path) || strings.EqualFold(filepath.Ext(path), extHTML) {
		return false
	}
	var header strings.Builder
	for _, line := range strings.Split(text, "\n") {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "#") && !strings.HasPrefix(trimmed, "//") && !strings.HasPrefix(trimmed, ";") {
			break
		}
		header.WriteString(trimmed + "\n")
	}
	return containsBannerMarker(header.String())
}

// IsMarkdownExt reports whether path has a markdown-family extension, the files
// whose headers are HTML comments.
func IsMarkdownExt(path string) bool {
	switch strings.ToLower(filepath.Ext(path)) {
	case ".md", ".mdc", ".markdown", ".mdx":
		return true
	}
	return false
}

// containsBannerMarker reports whether header holds a string generated headers
// and rule banners carry.
func containsBannerMarker(header string) bool {
	for _, marker := range [...]string{"GENERATED FILE", "Generated by ai-rulez", "AI-RULEZ ::"} {
		if strings.Contains(header, marker) {
			return true
		}
	}
	return false
}

// FrontmatterEnd locates a leading YAML frontmatter block by the rules of
// internal/frontmatter. open reports that the content starts with a fence line;
// end is the offset just past the closing fence line (its terminator included),
// or 0 when the block is not closed. One helper serves the banner check, hash
// injection and header stripping, so files with CRLF line endings (a checkout
// with autocrlf, an editor that converts them) are read the same way as the LF
// files ai-rulez writes.
func FrontmatterEnd(s string) (end int, open bool) {
	block := frontmatter.SplitString(s)
	if !block.Closed {
		return 0, block.Present
	}
	return len(s) - len(block.Body), true
}

// SkipEOL drops one or two line breaks (LF or CRLF) from the start of s: the
// blank line that follows a banner.
func SkipEOL(s string) string {
	for i := 0; i < 2; i++ {
		switch {
		case strings.HasPrefix(s, "\r\n"):
			s = s[2:]
		case strings.HasPrefix(s, "\n"):
			s = s[1:]
		default:
			return s
		}
	}
	return s
}

// BodyEdited reports whether content, read from path, no longer matches the
// stored Content-Hash of its header. Without a stored hash the file cannot be
// judged and is not reported.
func BodyEdited(stored, content, path string) bool {
	if stored == "" {
		return false
	}
	// The hash is taken before generate normalizes the file to one trailing
	// newline, so any run of trailing newlines in the rendering may have been
	// collapsed; accept every run the generator can produce.
	trimmed := strings.TrimRight(StripHeader(content, path), "\n")
	for newlines := 0; newlines <= MaxHashedTrailingNewlines; newlines++ {
		if templates.HashContent(trimmed+strings.Repeat("\n", newlines)) == stored {
			return false
		}
	}
	return true
}

// ScanHashes scans the header of a file and returns the Content-Hash and
// Source-Hash values found there (empty strings if missing), and whether a hash
// was found inside the frontmatter block. A file starting with a YAML
// frontmatter block is scanned through the closing "---" however long the block
// is, then up to maxHeaderLines more lines for the banner; other files are
// scanned for maxHeaderLines lines. Lines of any length are handled and CRLF is
// accepted.
func ScanHashes(r io.Reader) (contentHash, sourceHash string, inFrontmatterBlock bool) {
	st := hashScan{budget: maxHeaderLines}
	reader := bufio.NewReader(r)
	for first := true; ; first = false {
		raw, readErr := reader.ReadString('\n')
		if raw == "" && readErr != nil {
			break // EOF, or a read error: end with what was found
		}
		if st.line(strings.TrimRight(raw, "\r\n"), first) || readErr != nil {
			break
		}
	}
	return st.contentHash, st.sourceHash, st.inBlock
}

// hashScan is the state of ScanHashes.
type hashScan struct {
	contentHash, sourceHash string
	inFrontmatter           bool // currently inside the frontmatter block
	inBlock                 bool // a hash was found inside the frontmatter block
	budget                  int  // lines left outside the frontmatter block
}

// line consumes one line and reports whether the scan is finished.
func (h *hashScan) line(raw string, first bool) bool {
	switch {
	case first && raw == "---":
		h.inFrontmatter = true
		return false
	case h.inFrontmatter && raw == "---":
		h.inFrontmatter = false
		return false
	case !h.inFrontmatter:
		h.budget--
		if h.budget < 0 {
			return true
		}
	}
	c, s := HashFromLine(raw)
	if c != "" {
		h.contentHash = c
	}
	if s != "" {
		h.sourceHash = s
	}
	if (c != "" || s != "") && h.inFrontmatter {
		h.inBlock = true
	}
	return h.contentHash != "" && h.sourceHash != ""
}

// HashFromLine extracts a Content-Hash or Source-Hash value from one header
// line, regardless of comment style (HTML, hash, slash, semicolon).
func HashFromLine(raw string) (contentHash, sourceHash string) {
	stripped := strings.TrimSpace(raw)
	for _, prefix := range [...]string{"<!--", "-->", "//", "#", ";", "/*", "*/"} {
		stripped = strings.TrimPrefix(stripped, prefix)
	}
	stripped = strings.TrimSpace(stripped)
	switch {
	case strings.HasPrefix(stripped, "Content-Hash: "):
		return strings.TrimPrefix(stripped, "Content-Hash: "), ""
	case strings.HasPrefix(stripped, "Source-Hash: "):
		return "", strings.TrimPrefix(stripped, "Source-Hash: ")
	}
	return "", ""
}

// StripHeader removes the header comment from generated content, returning
// only the body. The header format depends on the output file extension.
//
// Detection runs in the same priority order as the generator's hash injection so
// that the body passed to the body hash is symmetric with the body the injection
// sees. Files may have multiple header layers (e.g. devin rule files have
// trigger frontmatter THEN a generated-file banner) — we strip them all,
// otherwise the banner's per-run timestamp would leak into the body hash.
func StripHeader(content, outputPath string) string {
	ext := strings.ToLower(filepath.Ext(outputPath))

	// 1. YAML frontmatter (skill/agent files, plus rule files that prepend
	// trigger frontmatter). Strip and continue — there may be a banner after.
	if end, _ := FrontmatterEnd(content); end > 0 {
		// Drop a single leading blank line so banner detection works against
		// either "---\n\n<!--" or "---\n<!--" forms.
		content = strings.TrimPrefix(strings.TrimPrefix(content[end:], "\r"), "\n")
	}

	switch ext {
	case ".mdc", ".md", ".markdown", ".mdx", ".html":
		// Only a banner at the very start (after the frontmatter) is a header: a
		// "-->" further down belongs to the body (fenced HTML, comments) and
		// stripping up to it would truncate the hashed body. "# Heading" is a
		// heading in markdown, not a line comment, so no line-comment stripping.
		if !strings.HasPrefix(content, "<!--") {
			return content
		}
		if idx := strings.Index(content, "-->"); idx >= 0 {
			return SkipEOL(content[idx+len("-->"):])
		}
		return content
	default:
		// Line-prefix comments (#, //, ;) — also covers .mdc which uses
		// "# title\n\nbody" with the title acting as a heading-shaped header.
		lines := strings.Split(content, "\n")
		i := 0
		for i < len(lines) {
			trimmed := strings.TrimSpace(lines[i])
			if trimmed == "" {
				i++
				break
			}
			isComment := strings.HasPrefix(trimmed, "#") ||
				strings.HasPrefix(trimmed, "//") ||
				strings.HasPrefix(trimmed, ";")
			if !isComment {
				break
			}
			i++
		}
		if i >= len(lines) {
			return ""
		}
		return strings.Join(lines[i:], "\n")
	}
}
