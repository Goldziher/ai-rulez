package templates_test

import (
	"testing"

	"github.com/stretchr/testify/assert"

	"github.com/Goldziher/ai-rulez/v5/internal/config"
	"github.com/Goldziher/ai-rulez/v5/internal/templates"
)

func nestedConfig(nested string, text string) *config.Config {
	return &config.Config{
		Name: "N", ConfigDirName: ".ai-rulez", RootRel: "svc/api", NestedRoot: true,
		Header: &config.HeaderConfig{Style: "detailed", Nested: nested, Text: text},
	}
}

// A nested root repeats none of the outer root's boilerplate (#364).
func TestHeader_NestedRootIsCompactByDefault(t *testing.T) {
	t.Parallel()

	header := templates.GenerateHeader(createTemplateData("N", nestedConfig("", "")))
	assert.Equal(t, "<!--\nGenerated by ai-rulez from svc/api/.ai-rulez/config.toml; do not edit\n-->\n\n", header)
}

func TestHeader_NestedRootOmit(t *testing.T) {
	t.Parallel()

	assert.Equal(t, "", templates.GenerateHeader(createTemplateData("N", nestedConfig(config.HeaderNestedOmit, ""))))
}

func TestHeader_NestedRootInheritKeepsTheFullHeader(t *testing.T) {
	t.Parallel()

	header := templates.GenerateHeader(createTemplateData("N", nestedConfig(config.HeaderNestedInherit, "")))
	assert.Contains(t, header, "WHAT IS AI-RULEZ")
	assert.Contains(t, header, "Source: svc/api/.ai-rulez/config.toml")
}

func TestHeader_NestedRootKeepsCustomTextUnlessModeIsExplicit(t *testing.T) {
	t.Parallel()

	kept := templates.GenerateHeader(createTemplateData("N", nestedConfig("", "my banner")))
	assert.Contains(t, kept, "my banner")

	replaced := templates.GenerateHeader(createTemplateData("N", nestedConfig(config.HeaderNestedCompact, "my banner")))
	assert.NotContains(t, replaced, "my banner")
	assert.Contains(t, replaced, "Generated by ai-rulez from svc/api/.ai-rulez/config.toml; do not edit")
}

func TestHeader_OuterRootIgnoresNestedMode(t *testing.T) {
	t.Parallel()

	cfg := &config.Config{Name: "N", Header: &config.HeaderConfig{Style: "minimal", Nested: config.HeaderNestedOmit}}
	assert.Contains(t, templates.GenerateHeader(createTemplateData("N", cfg)), "NEVER edit this file")
}

// A nested root's header must name its own config, relative to the outermost
// root, not the repository-root config (#361).
func TestHeader_NestedRootSourceIsRepoRelative(t *testing.T) {
	t.Parallel()

	for _, style := range []string{"detailed", "compact", "minimal"} {
		t.Run(style, func(t *testing.T) {
			t.Parallel()
			data := createTemplateData("N", &config.Config{
				Name:          "N",
				ConfigDirName: ".ai-rulez",
				RootRel:       "products/em/webapps",
				Header:        &config.HeaderConfig{Style: style},
			})
			header := templates.GenerateHeader(data)
			assert.Contains(t, header, "Source: products/em/webapps/.ai-rulez/config.toml")
			assert.NotContains(t, header, "Source: .ai-rulez/")
		})
	}
}
