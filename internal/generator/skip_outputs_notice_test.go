package generator

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const skipInstructions = "agents_md = true\nskip_outputs = [\"instructions\"]\n"

// unmanagedNoticeProject generates every output, then excludes the instruction
// files, so the generated CLAUDE.md is left behind with its header.
func unmanagedNoticeProject(t *testing.T) string {
	t.Helper()
	root := skipProject(t, "")
	require.NoError(t, skipGenerator(t, root).Generate(""))
	writeAgentsMDProject(t, root, agentsMDConfig([]string{"claude", "gemini", "codex"}, skipInstructions, skipMCPTable))
	return root
}

func TestSkipOutputs_UnmanagedNoticeIsGivenOncePerFile(t *testing.T) {
	tests := []struct {
		name string
		// run is what follows the first generate, which gives the notice.
		run func(t *testing.T, root string)
	}{
		{name: "generate again", run: func(t *testing.T, root string) {
			require.NoError(t, skipGenerator(t, root).Generate(""))
		}},
		{name: "generate twice more", run: func(t *testing.T, root string) {
			require.NoError(t, skipGenerator(t, root).Generate(""))
			require.NoError(t, skipGenerator(t, root).Generate(""))
		}},
		{name: "check", run: func(t *testing.T, root string) {
			_, err := skipGenerator(t, root).CheckDrift("")
			require.NoError(t, err)
		}},
		{name: "clean", run: func(t *testing.T, root string) {
			_, err := skipGenerator(t, root).Clean("", CleanOptions{})
			require.NoError(t, err)
		}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// Arrange
			warned := quietWarnings(t)
			root := unmanagedNoticeProject(t)
			require.NoError(t, skipGenerator(t, root).Generate(""))
			require.Equal(t, 1, countContaining(*warned, "CLAUDE.md was generated by an earlier run"), "the first run gives the notice: %v", *warned)

			// Act
			tt.run(t, root)

			// Assert
			assert.Equal(t, 1, countContaining(*warned, "CLAUDE.md was generated by an earlier run"), "later runs stay quiet: %v", *warned)
			assert.FileExists(t, filepath.Join(root, "CLAUDE.md"))
		})
	}
}

func TestSkipOutputs_UnmanagedNoticeReturnsForARecreatedFile(t *testing.T) {
	// Arrange
	warned := quietWarnings(t)
	root := unmanagedNoticeProject(t)
	require.NoError(t, skipGenerator(t, root).Generate(""))
	claude := filepath.Join(root, "CLAUDE.md")
	generated, err := os.ReadFile(claude)
	require.NoError(t, err)
	require.NoError(t, os.Remove(claude))
	require.NoError(t, skipGenerator(t, root).Generate(""), "the deleted file is forgotten")

	// Act: the same generated file appears again
	require.NoError(t, os.WriteFile(claude, generated, 0o644))
	require.NoError(t, skipGenerator(t, root).Generate(""))

	// Assert
	assert.Equal(t, 2, countContaining(*warned, "CLAUDE.md was generated by an earlier run"), "%v", *warned)
}
