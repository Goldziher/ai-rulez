package lint

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestTrapsRecognizeTheRealGeneratedHeader(t *testing.T) {
	const cfg = ".ai-rulez/config.toml"

	t.Run("a generated file with the real header is an error, a preset bug, with no fix", func(t *testing.T) {
		findings := trapFindings(t, map[string]string{
			cfg:                    trapConfig(`"cursor"`, ""),
			".cursor/rules/gen.md": realBanner + "# g\n",
		})

		var got []Finding
		for _, f := range findings {
			if f.Code == CodeCursorRuleExtension {
				got = append(got, f)
			}
		}
		require.Len(t, got, 1, dump(findings))
		assert.Equal(t, SeverityError, got[0].Severity)
		assert.Contains(t, got[0].Message, "bug in the preset")
		assert.Nil(t, got[0].meta().Fix, "ai-rulez owns the file: a fix would be overwritten")
	})

	t.Run("a gitignored output with the real header is scanned", func(t *testing.T) {
		findings := trapFindings(t, map[string]string{
			cfg:                         trapConfig(`"claude"`, ""),
			".gitignore":                ".claude/skills/\n",
			".claude/skills/g/SKILL.md": "---\nname: g\nallowed_tools: Read\n---\n" + realBanner + "body\n",
			".claude/skills/h/SKILL.md": "---\nname: h\nallowed_tools: Read\n---\nhandwritten\n",
		})

		var hits []string
		for _, f := range findings {
			if f.Code == "AR9C7" {
				hits = append(hits, f.File)
			}
		}
		require.Len(t, hits, 1, dump(findings))
		assert.True(t, strings.HasSuffix(hits[0], ".claude/skills/g/SKILL.md"))
	})

	t.Run("a quoted marker below the header leaves the file handwritten", func(t *testing.T) {
		findings := trapFindings(t, map[string]string{
			cfg:                    trapConfig(`"cursor"`, ""),
			".cursor/rules/doc.md": "# doc\n\n<!-- Generated by ai-rulez -->\n",
		})

		for _, f := range findings {
			if f.Code == CodeCursorRuleExtension {
				assert.Equal(t, SeverityWarning, f.Severity)
				assert.NotContains(t, f.Message, "bug in the preset")
			}
		}
	})
}
