package lint

import (
	"context"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const (
	spoofLeak  = "key = ghp_abcdefghijklmnopqrstuvwxyz0123456789\n"
	realBanner = "<!--\n🤖 AI-RULEZ :: GENERATED FILE — DO NOT EDIT\nProject: t\n-->\n\n"
)

func detectTargets(t *testing.T, files map[string]string) *Targets {
	t.Helper()
	root := t.TempDir()
	writeFiles(t, root, files)
	gitAdd(t, root)
	tree, err := LoadTree(root)
	require.NoError(t, err)
	targets, err := ResolveTargets(context.Background(), tree, TargetSpec{Detect: true, Cwd: root})
	require.NoError(t, err)
	return targets
}

func TestDetectLintsAFileThatOnlyQuotesTheGeneratedMarker(t *testing.T) {
	tests := []struct {
		name string
		body string
	}{
		{name: "marker after a heading", body: "# Notes\n\n<!-- Generated by ai-rulez -->\n" + spoofLeak},
		{name: "real header text deep in the body", body: "# Notes\n\nAI-RULEZ :: GENERATED FILE\n" + spoofLeak},
		{name: "marker inside a fenced block", body: "# Notes\n\n```\n<!-- Generated by ai-rulez -->\n```\n" + spoofLeak},
		{name: "marker in a later comment", body: "<!-- todo -->\n\n<!-- Generated by ai-rulez -->\n" + spoofLeak},
		{name: "banner with a Content-Hash its body does not match", body: "<!-- Generated by ai-rulez\nContent-Hash: blake3:00 -->\n\n" + spoofLeak},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			targets := detectTargets(t, map[string]string{"sub/AGENTS.md": tc.body})

			assert.Equal(t, []string{"sub/AGENTS.md"}, targets.Rels(), "the file is handwritten and must be linted")
		})
	}
}

func TestDetectNamesAConventionalFileItSkipsAsGenerated(t *testing.T) {
	tests := []struct {
		name string
		body string
	}{
		{name: "real header", body: realBanner + "# a\n"},
		{name: "old banner", body: "<!-- Generated by ai-rulez from x.md. -->\n# a\n"},
		{name: "byte order mark before the header", body: "\xef\xbb\xbf" + realBanner + "# a\n"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			targets := detectTargets(t, map[string]string{"sub/AGENTS.md": tc.body})

			assert.Empty(t, targets.Rels())
			assert.Contains(t, strings.Join(targets.Notices(), "\n"), "sub/AGENTS.md: not linted (generated file")
		})
	}
}

func TestDetectFindsNestedClaudeDirectories(t *testing.T) {
	files := map[string]string{
		"CLAUDE.md":                  "# root\n",
		"sub/CLAUDE.md":              "Follow the `r` rule. Delegate to subagent_type: a.\n",
		"sub/.claude/rules/r.md":     "---\npaths:\n  - \"**/*.py\"\n---\nRule r body.\n",
		"sub/.claude/commands/c.md":  "---\ndescription: Do the c thing for this repo.\n---\nDo c.\n",
		"sub/.claude/agents/a.md":    "---\nname: a\ndescription: Agent a. Use when asked to do a.\n---\nBody.\n",
		"deep/er/.claude/rules/q.md": "Rule q body.\n",
	}
	want := []string{
		"CLAUDE.md",
		"deep/er/.claude/rules/q.md",
		"sub/.claude/agents/a.md",
		"sub/.claude/commands/c.md",
		"sub/.claude/rules/r.md",
		"sub/CLAUDE.md",
	}
	tests := []struct {
		name string
		git  bool
	}{
		{name: "git repository", git: true},
		{name: "directory without git", git: false},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			root := t.TempDir()
			writeFiles(t, root, files)
			if tc.git {
				gitAdd(t, root)
			}
			tree, err := LoadTree(root)
			require.NoError(t, err)

			targets, err := ResolveTargets(context.Background(), tree, TargetSpec{Detect: true, Cwd: root})

			require.NoError(t, err)
			assert.Equal(t, want, targets.Rels())
		})
	}
}
