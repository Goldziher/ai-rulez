// setOutputsFlag turns validate --outputs on for one test.
func setOutputsFlag(t *testing.T) {
	t.Helper()
	f := ValidateCmd.Flags().Lookup(flagLintOutputs)
	require.NotNil(t, f, "validate has no --%s", flagLintOutputs)
	require.NoError(t, f.Value.Set("true"))
	f.Changed = true
	t.Cleanup(func() {
		_ = f.Value.Set("false")
		f.Changed = false
	})
}

func findingsOf(rep *lint.Report, code string) []lint.Finding {
	var out []lint.Finding
	for i := range rep.Findings {
		if rep.Findings[i].Code == code {
			out = append(out, rep.Findings[i])
		}
	}
	return out
}

func TestOutputsFlagIsStrictOnly(t *testing.T) {
	t.Cleanup(func() { validateStrict = false })
	setOutputsFlag(t)
	validateStrict = false
	require.Error(t, checkStrictFlags(), "--outputs with --config-only must be rejected")
	validateStrict = true
	require.NoError(t, checkStrictFlags())
}

