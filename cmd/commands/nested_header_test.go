// nestedHeaderRepo builds a repository whose root and svc/api both hold an
// ai-rulez config, and makes it the working directory.
func nestedHeaderRepo(t *testing.T, nestedHeader string) string {
	t.Helper()
	root := t.TempDir()
	require.NoError(t, os.Mkdir(filepath.Join(root, ".git"), 0o755))
	rootCfg := validRootConfig + "\n[header]\nhashes = \"full\"\n"
	writeFile(t, filepath.Join(root, ".ai-rulez", "config.toml"), rootCfg)
	writeFile(t, filepath.Join(root, ".ai-rulez", "rules", "r.md"), "---\npriority: high\n---\nRoot rule\n")
	writeFile(t, filepath.Join(root, "svc", "api", ".ai-rulez", "config.toml"), rootCfg+nestedHeader)
	writeFile(t, filepath.Join(root, "svc", "api", ".ai-rulez", "rules", "r.md"), "---\npriority: high\n---\nNested rule\n")
	chdir(t, root)
	progress.SetQuiet(true)
	t.Cleanup(func() {
		progress.SetQuiet(false)
		pluginMode, dryRun, profile, validateRecursive = false, false, "", false
	})
	pluginMode, dryRun, profile = false, false, ""
	return root
}

func TestNestedRootHeader_GenerateAndCheckAgree(t *testing.T) {
	tests := []struct {
		name         string
		nestedHeader string
		want         func(t *testing.T, nested string)
	}{
		{"compact by default", "", func(t *testing.T, nested string) {
			assert.Contains(t, nested, "Generated by ai-rulez from svc/api/.ai-rulez/config.toml; do not edit")
			assert.Contains(t, nested, "Content-Hash: blake3:")
			assert.NotContains(t, nested, "NEVER edit this file")
		}},
		{"omit", "nested = \"omit\"\n", func(t *testing.T, nested string) {
			assert.False(t, strings.HasPrefix(nested, "<!--"), "no header block")
			assert.NotContains(t, nested, "Generated by ai-rulez")
			assert.Contains(t, nested, "# ok")
		}},
		{"inherit", "nested = \"inherit\"\n", func(t *testing.T, nested string) {
			assert.Contains(t, nested, "NEVER edit this file")
			assert.Contains(t, nested, "Source: svc/api/.ai-rulez/config.toml")
		}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := nestedHeaderRepo(t, tt.nestedHeader)
			require.Equal(t, 0, runRecursiveGenerate(), "generate")

			outer, err := os.ReadFile(filepath.Join(root, "CLAUDE.md"))
			require.NoError(t, err)
			assert.Contains(t, string(outer), "Source: .ai-rulez/config.toml", "the outer root keeps its full header")
			nested, err := os.ReadFile(filepath.Join(root, "svc", "api", "CLAUDE.md"))
			require.NoError(t, err)
			tt.want(t, string(nested))

			assert.Equal(t, 0, runDriftCheck(true), "recursive check of fresh output")
			require.Equal(t, 0, runRecursiveGenerate(), "a second generate keeps its own output, header or not")

			useConfigFile(t, filepath.Join(root, "svc", "api", ".ai-rulez", "config.toml"))
			assert.Equal(t, 0, runDriftCheck(false), "single-root check renders the same header")

			f, err := os.OpenFile(filepath.Join(root, "svc", "api", "CLAUDE.md"), os.O_APPEND|os.O_WRONLY, 0o644)
			require.NoError(t, err)
			_, err = f.WriteString("hand edit\n")
			require.NoError(t, err)
			require.NoError(t, f.Close())
			assert.Equal(t, exitDrift, runDriftCheck(false), "an edit to the nested file is drift")
		})
	}
}
