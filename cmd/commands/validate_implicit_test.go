// implicitProject writes files under a fresh directory and makes it the working
// directory. There is no configuration among them unless the test adds one.
func implicitProject(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, body := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
		require.NoError(t, os.WriteFile(p, []byte(body), 0o644))
	}
	t.Chdir(root)
	return root
}

func lintImplicit(t *testing.T) *lint.Report {
	t.Helper()
	cfg, err := loadLintConfig(t.Context(), config.WithFrontmatterErrors())
	require.NoError(t, err)
	require.True(t, cfg.Implicit)
	rep, err := strictLint(t.Context(), cfg)
	require.NoError(t, err)
	return rep
}

func TestLoadLintConfigFallsBackToAnImplicitConfig(t *testing.T) {
	tests := []struct {
		name  string
		files map[string]string
		want  []string // codes expected
		none  []string // codes that must be absent
	}{
		{name: "empty directory, no git"},
		{
			name:  "a skill with no description",
			files: map[string]string{"skills/loose/SKILL.md": "---\nname: loose\n---\nbody\n"},
			want:  []string{lint.CodeDescriptionMissing},
		},
		{
			name:  "AGENTS.md alone",
			files: map[string]string{"AGENTS.md": "# Rules\n\nRun the tests.\n"},
			none:  []string{lint.CodeSecretDetected},
		},
		{
			name:  "a credential in AGENTS.md",
			files: map[string]string{"AGENTS.md": "# Rules\n\nkey = ghp_abcdefghijklmnopqrstuvwxyz0123456789\n"},
			want:  []string{lint.CodeSecretDetected},
		},
		{
			name:  "a hand-written .claude skill",
			files: map[string]string{".claude/skills/x/SKILL.md": "---\nname: x\n---\nbody\n"},
			want:  []string{lint.CodeDescriptionMissing},
		},
		{
			name:  "an .ai-rulez content tree without config.toml",
			files: map[string]string{".ai-rulez/skills/y/SKILL.md": "---\nname: y\n---\nbody\n"},
			want:  []string{lint.CodeDescriptionMissing},
		},
		{
			name:  "a marketplace in its conventional place",
			files: map[string]string{".claude-plugin/marketplace.json": `{"name":"acme","plugins":[{"name":"a","source":"plugins/a"}]}`},
			want:  []string{lint.CodePluginManifest},
		},
		{
			name:  "a generated file is an output, not a source",
			files: map[string]string{"skills/gen/SKILL.md": "<!-- Generated by ai-rulez -->\n---\nname: gen\n---\nbody\n"},
			none:  []string{lint.CodeDescriptionMissing},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			implicitProject(t, tt.files)

			rep := lintImplicit(t)

			got := map[string]bool{}
			for _, f := range rep.Findings {
				got[f.Code] = true
			}
			for _, code := range tt.want {
				assert.True(t, got[code], "want %s, got %v", code, rep.Findings)
			}
			for _, code := range tt.none {
				assert.False(t, got[code], "unexpected %s in %v", code, rep.Findings)
			}
			if len(tt.want) == 0 && len(tt.none) == 0 {
				assert.Empty(t, rep.Findings)
			}
		})
	}
}

func TestLoadLintConfigPrefersARealConfiguration(t *testing.T) {
	implicitProject(t, map[string]string{
		".ai-rulez/config.toml": "version = \"5.0\"\nname = \"p\"\ngitignore = false\nagents_md = false\npresets = [\"claude\"]\n",
	})

	cfg, err := loadLintConfig(t.Context())

	require.NoError(t, err)
	assert.False(t, cfg.Implicit)
	assert.Equal(t, "p", cfg.Name)
}

func TestLoadLintConfigUsesTheConfigurationOfAParentDirectory(t *testing.T) {
	root := implicitProject(t, map[string]string{
		".ai-rulez/config.toml": "version = \"5.0\"\nname = \"p\"\ngitignore = false\nagents_md = false\npresets = [\"claude\"]\n",
		"pkg/a.txt":             "x",
	})
	t.Chdir(filepath.Join(root, "pkg"))

	cfg, err := loadLintConfig(t.Context())

	require.NoError(t, err, "a subdirectory of a configured project is that project, never an implicit one")
	assert.False(t, cfg.Implicit)
	assert.Equal(t, "p", cfg.Name)
}

