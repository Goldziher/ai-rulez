func TestExplicitPathReplacesDetectionInAnImplicitRun(t *testing.T) {
	implicitProject(t, map[string]string{
		"AGENTS.md":            "# Rules\n\nkey = ghp_abcdefghijklmnopqrstuvwxyz0123456789\n",
		"market/index.json":    `{"name":"acme","owner":{"name":"A"},"plugins":[{"name":"a","source":"plugins/a"}]}`,
		".ai-rulez/rules/r.md": "# r\n\nkey = ghp_abcdefghijklmnopqrstuvwxyz0123456789\n",
	})
	setTargetFlags(t, []string{"market"}, nil)

	rep := lintImplicit(t)

	codes := map[string]bool{}
	for _, f := range rep.Findings {
		codes[f.Code] = true
	}
	assert.True(t, codes[lint.CodePluginManifest], "the named directory is linted")
	assert.False(t, codes[lint.CodeSecretDetected], "nothing is detected implicitly when files are named: %v", rep.Findings)
}

const implicitSecretDoc = "# Rules\n\nkey = ghp_abcdefghijklmnopqrstuvwxyz0123456789\n"

func TestRecursiveValidateWithoutConfigurationLintsTheImplicitRoot(t *testing.T) {
	tests := []struct {
		name     string
		files    map[string]string
		paths    []string
		wantCode int
	}{
		{name: "a secret in a nested AGENTS.md fails the run", files: map[string]string{"a/AGENTS.md": implicitSecretDoc}, wantCode: exitStrictFindings},
		{name: "a clean tree passes", files: map[string]string{"a/AGENTS.md": "# Rules\n\nBe kind.\n"}, wantCode: 0},
		{
			name:     "--path replaces the detection",
			files:    map[string]string{"AGENTS.md": implicitSecretDoc, "docs/ok.md": "# ok\n"},
			paths:    []string{"docs/ok.md"},
			wantCode: 0,
		},
		{
			name:     "--path reaches a secret below the root",
			files:    map[string]string{"docs/bad.md": implicitSecretDoc},
			paths:    []string{"docs/bad.md"},
			wantCode: exitStrictFindings,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			implicitProject(t, tt.files)
			strictTreeCache = &lint.Loader{}
			t.Cleanup(func() { strictTreeCache = &lint.Loader{}; validateStrict, validateRecursive = false, false })
			validateStrict, validateRecursive = true, true
			setTargetFlags(t, tt.paths, nil)

			var code int
			stdout, stderr := capture(t, func() { code = runRecursiveValidate() })

			assert.Equal(t, tt.wantCode, code, "stdout: %s\nstderr: %s", stdout, stderr)
			assert.NotContains(t, stdout+stderr, "No configuration files found")
		})
	}
}

func TestImplicitRunRefusesTheHomeDirectoryWithoutSuggestingPathFlags(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("USERPROFILE", home)
	t.Chdir(home)

	_, err := loadLintConfig(t.Context())

	require.Error(t, err)
	oe, ok := oops.AsOops(err)
	require.True(t, ok)
	assert.Contains(t, oe.Hint(), "inside a project directory")
	assert.NotContains(t, oe.Hint(), "--path")
	assert.NotContains(t, oe.Hint(), "--glob")
}

// With a configuration, the harness files nobody generated are linted as well; the generated ones are outputs.
func TestManagedProjectLintsHandWrittenHarnessFiles(t *testing.T) {
	const configToml = "version = \"5.0\"\nname = \"p\"\ngitignore = false\nagents_md = false\npresets = [\"claude\"]\n"
	const head = "---\nname: hand\ndescription: Hand written. Use when testing.\n---\n"
	tests := []struct {
		name  string
		files map[string]string
		want  bool
	}{
		{"a hand-written skill with a dangling reference", map[string]string{".claude/skills/hand/SKILL.md": head + "Run the `ghost-skill` skill.\n"}, true},
		{"a hand-written rule with a secret", map[string]string{".claude/rules/r.md": "# R\nkey = ghp_abcdefghijklmnopqrstuvwxyz0123456789\n"}, true},
		{"a generated file is an output", map[string]string{".claude/skills/hand/SKILL.md": "<!-- Generated by ai-rulez -->\n" + head + "Run the `ghost-skill` skill.\n"}, false},
		{"a clean hand-written skill", map[string]string{".claude/skills/hand/SKILL.md": head + "Run it.\n"}, false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// Arrange
			implicitProject(t, tt.files)
			require.NoError(t, os.MkdirAll(".ai-rulez", 0o755))
			require.NoError(t, os.WriteFile(".ai-rulez/config.toml", []byte(configToml), 0o644))
			cfg, err := loadLintConfig(t.Context(), config.WithFrontmatterErrors())
			require.NoError(t, err)

			// Act
			rep, err := strictLint(withUnmanagedLint(t.Context()), cfg)

			// Assert
			require.NoError(t, err)
			require.False(t, cfg.Implicit)
			codes := map[string]bool{}
			for _, f := range rep.Findings {
				codes[f.Code] = true
			}
			assert.Equal(t, tt.want, codes[lint.CodeReferenceUnknown] || codes[lint.CodeSecretDetected], "findings: %v", rep.Findings)
		})
	}
}

// Only a validate run lints the files the configuration does not list; catalog and publish keep to its content.
func TestOtherCommandsLintOnlyTheConfiguredContent(t *testing.T) {
	// Arrange
	implicitProject(t, map[string]string{".claude/skills/hand/SKILL.md": "---\nname: hand\ndescription: Hand written. Use when testing.\n---\nRun the `ghost-skill` skill.\n"})
	require.NoError(t, os.MkdirAll(".ai-rulez", 0o755))
	require.NoError(t, os.WriteFile(".ai-rulez/config.toml", []byte("version = \"5.0\"\nname = \"p\"\ngitignore = false\nagents_md = false\npresets = [\"claude\"]\n"), 0o644))
	cfg, err := loadLintConfig(t.Context(), config.WithFrontmatterErrors())
	require.NoError(t, err)

	// Act
	rep, err := strictLint(t.Context(), cfg)
	control, controlErr := strictLint(withUnmanagedLint(t.Context()), cfg)

	// Assert
	require.NoError(t, err)
	require.NoError(t, controlErr)
	var controlCodes []string
	for _, f := range control.Findings {
		controlCodes = append(controlCodes, f.Code)
	}
	require.Contains(t, controlCodes, lint.CodeReferenceUnknown, "control: a validate run lints the hand-written file")
	for _, f := range rep.Findings {
		assert.NotEqual(t, lint.CodeReferenceUnknown, f.Code, "an unlisted file was linted: %v", f)
	}
}
