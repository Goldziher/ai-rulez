// realGeneratedProject generates a project for real (a rule, a skill and an agent for
// claude), drops its configuration and returns its root as the working directory.
func realGeneratedProject(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{
		".ai-rulez/config.toml":            "version = \"5.0\"\nname = \"p\"\ngitignore = false\npresets = [\"claude\"]\n",
		".ai-rulez/rules/style.md":         "---\npriority: high\n---\n# Style\n\nKeep it short.\n",
		".ai-rulez/skills/helper/SKILL.md": "---\nname: helper\ndescription: Use when helping\n---\n# Helper\n\nHelp.\n",
		".ai-rulez/agents/reviewer.md":     "---\nname: reviewer\ndescription: Use when reviewing\n---\n# Reviewer\n\nReview.\n",
	}
	for name, body := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
		require.NoError(t, os.WriteFile(p, []byte(body), 0o644))
	}
	t.Chdir(root)
	cfg, err := config.LoadConfig(t.Context(), root, config.WithoutRemote())
	require.NoError(t, err)
	require.NoError(t, generator.NewGenerator(cfg).Generate(""))
	require.NoError(t, os.RemoveAll(filepath.Join(root, ".ai-rulez")))
	return root
}

func TestEveryMarkdownFileGenerateWroteIsRecognisedAsGenerated(t *testing.T) {
	root := realGeneratedProject(t)
	var seen []string

	require.NoError(t, filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".md") {
			return err
		}
		rel, _ := filepath.Rel(root, p) //nolint:errcheck // p is below root
		data, err := os.ReadFile(p)
		require.NoError(t, err)
		seen = append(seen, filepath.ToSlash(rel))
		assert.True(t, genmark.IsGeneratedOutput(filepath.ToSlash(rel), data), "%s is a file generate wrote", rel)
		return nil
	}))

	assert.Contains(t, seen, "AGENTS.md")
	assert.Contains(t, seen, ".claude/skills/helper/SKILL.md")
	assert.Contains(t, seen, ".claude/agents/reviewer.md")
}

func TestImplicitRunSkipsRealGeneratedFilesWithANoticeAndLintsASpoof(t *testing.T) {
	root := realGeneratedProject(t)
	spoof := "# Notes\n\n<!-- Generated by ai-rulez -->\n\nkey = ghp_abcdefghijklmnopqrstuvwxyz0123456789\n"
	require.NoError(t, os.MkdirAll(filepath.Join(root, "sub"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, "sub", "AGENTS.md"), []byte(spoof), 0o644))

	rep := lintImplicit(t)

	got := findingsOf(rep, lint.CodeSecretDetected)
	require.Len(t, got, 1, "%v", rep.Findings)
	assert.Equal(t, "sub/AGENTS.md", got[0].File)
	notices := strings.Join(rep.Notices, "\n")
	assert.Contains(t, notices, "AGENTS.md: not linted (generated file", "a skipped conventional file is named")
}
